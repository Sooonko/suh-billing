/**
 * СӨХ-ийн данс руу ирдэг ӨӨР төрлийн орлогыг таних.
 *
 * ЯАГААД ХЭРЭГТЭЙ ВЭ:
 * СӨХ-ийн данс нь зөвхөн сарын хураамж (35,000₮) хүлээж авдаггүй —
 * зогсоол, граашны түрээс, цэвэрлэгээ, засварын мөнгө ч мөн тэр данс
 * руу ордог. 2026-08…09-ийн хуулгад 315 орлогоос 47 нь ийм байв
 * (6,300,000₮).
 *
 * ⚠️ ДҮНГЭЭР ЯЛГАЖ БОЛОХГҮЙ. Жишээ: 455,000₮ нь нэг талаас зогсоолын
 * жилийн төлбөр, нөгөө талаас 13 сарын СӨХ (35,000 × 13). Яг ижил дүн,
 * тэс өөр утга. Тиймээс ЗӨВХӨН гүйлгээний утгаар таьна.
 *
 * ⚠️ ЗОГСООЛЫН ДУГААР нь ТООТЫН дугаартай мөргөлддөг. «19 ТООТ ЗОГСООЛ»
 * гэдэг нь 19-р зогсоол, 19-р тоот БИШ. Таних дүрэмгүй бол задлагч
 * зогсоолын дугаарыг тоот гэж уншиж, мөнгийг буруу айлд оногдуулна.
 */

/** Зогсоол, граш, гараж — байрны бус үйлчилгээ */
const PARKING =
  /ЗОГСООЛ|ZOGSOOL|ГРААШ|ГРАШ|ГАРААШ|GRASH|GRAJ|GARASH|ГАРАЖ|GARAGE|GARAJ/i;

/** Цэвэрлэгээ, засвар, түрээс — эдгээр нь сарын хураамжид ордоггүй */
const SERVICE =
  /ЦЭВЭРЛЭГЭЭ|TSEWERLEGE|TSEVERLEGE|ЗАСВАР|ZASVAR|ТҮРЭЭС|TUREES|TURELS/i;

/** СӨХ-ийн хураамж гэдгийг ИЛЭРХИЙ хэлсэн эсэх */
const SOH_FEE = /СӨХ|СOХ|\bSOH\b|\bSUH\b|\bSOKH\b/i;

export type IncomeKind =
  /** Энгийн СӨХ-ийн хураамж */
  | 'SOH_FEE'
  /** Зогсоол / үйлчилгээ — айлын өрд оногдуулахгүй */
  | 'OTHER'
  /** ХОЛИМОГ: нэг гүйлгээнд хураамж ба зогсоол хоёулаа. Гараар хуваана. */
  | 'MIXED';

export interface IncomeClass {
  kind: IncomeKind;
  /** Админд харуулах шалтгаан */
  reason: string | null;
}

/**
 * Гүйлгээний утгаас орлогын төрлийг тогтооно.
 *
 * ХОЛИМОГ тохиолдлыг тусад нь ялгах нь ЧУХАЛ: «СӨХ ГРАШ 147 ТООТ 8 САР»
 * 50,000₮ гэдэг нь 35,000 хураамж + 15,000 зогсоол. Бүхэлд нь тооцохгүй
 * болговол айлын 35,000 төлөгдөөгүй хэвээр үлдэнэ.
 */
export function classifyIncome(description: string): IncomeClass {
  const other = PARKING.test(description) || SERVICE.test(description);
  if (!other) return { kind: 'SOH_FEE', reason: null };

  const what = PARKING.test(description) ? 'Зогсоол/граш' : 'Цэвэрлэгээ/засвар';

  // Утганд СӨХ гэж бас бичсэн бол хоёр төрлийн төлбөр нийлсэн байх магадлалтай
  if (SOH_FEE.test(description)) {
    return { kind: 'MIXED', reason: `${what} БА СӨХ-ийн хураамж нийлсэн — гараар хуваана` };
  }

  return { kind: 'OTHER', reason: `${what}-ны төлбөр — айлын өрд тооцохгүй` };
}
