/**
 * Гүйлгээний утгыг цэвэрлэх / нормчлох давхарга.
 *
 * Банкны хуулга дээр нэг л зүйлийг олон янзаар бичсэн байдаг:
 *   "184ТООТУС"  "2-236TOOT 6N SAR US"  "2R ORTS 289TOOT"  "323р байр 1 орц 127 тоот"
 *
 * Хамгийн эвгүй нь ЛАТИН/КИРИЛЛ ХОЛИЛДСОН байдаг явдал:
 *   "8CAP" гэдэг нь латин C-A-P үсгээр бичсэн "8САР".
 *
 * Бүх текстийг нэг цагаан толгой руу хөрвүүлэх нь АЮУЛТАЙ (жинхэнэ латин үгийг
 * эвдэнэ), тиймээс түлхүүр үг бүрийг латин/кирилл хосыг зэрэг зөвшөөрдөг
 * тэмдэгтийн ангиар (character class) илэрхийлнэ.
 */

// ---- Латин ба кирилл хос тэмдэгтүүд — "аль нь ч байж болно" ------------------
const A = '[АA]';
const S = '[СCS]'; // С (кирилл) · C (латин) · S
const R = '[РPR]'; // Р (кирилл) · P (латин) · R
const O = '[ОO]';
const T = '[ТT]';
const TS = '[ЦC]'; // Ц (кирилл) · C (латин)

/** "ТООТ" / "TOOT" / холимог */
export const TOOT = `${T}${O}${O}${T}`;
/** "САР" / "SAR" / "CAP" */
export const SAR = `${S}${A}${R}`;
/** "ORTS" (урт хувилбарыг ЭХЭЛЖ шалгана) / "ОРЦ" */
export const ORTS = `${O}${R}${T}${S}|${O}${R}${TS}`;
/**
 * "БАЙР" / "BAIR" / "BAYR"
 *
 * ⚠️ Кирилл хэсэгт зөвхөн Й — Я-г зөвшөөрч БОЛОХГҮЙ. "БАЯР" бол монголын
 * хамгийн түгээмэл хүний нэрүүдийн нэг бөгөөд гүйлгээний утганд тоотын
 * ЯГ АРААС нь ирдэг: "…2-297-БАЯР ЛХАГВАДОРЖ". Я-г зөвшөөрвөл "297-БАЯР"
 * нь "297-р байр" гэж уншигдаж, ТООТЫГ нь устгана.
 *
 * Латин талд "BAYAR" эрсдэлгүй — [IY]-ийн дараа шууд R шаардагддаг тул
 * B-A-Y-A-R таарахгүй.
 */
export const BAIR = `Б${A}Й${R}|B${A}[IY]${R}`;

/**
 * Үндсэн нормчлол:
 *  - том үсэг рүү хөрвүүлнэ
 *  - цэг, таслал, хаалт зэргийг зайгаар солино
 *  - олон зайг нэг болгоно
 *
 * NB: "-" тэмдэг ба цифрийг ХАДГАЛНА — "2-257" хэлбэр тоот таахад хэрэгтэй.
 */
export function normalize(raw: string): string {
  return raw
    .toUpperCase()
    .replace(/[.,;:/\\()[\]"'`_]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// ---- "Дуут" хэсгүүд: тоо агуулдаг ч ТООТ БИШ --------------------------------

/** 7+ оронтой тоо = утас / дансны дугаар. Тоот хэзээ ч ийм урт биш. */
const RE_LONG_NUMBER = /\d{7,}/g;

/**
 * "7 SAR" · "8CAP" · "6N SAR" · "7-SAR" · "6 7 САРЫН" (олон сар хамт)
 *
 * ⚠️ ХАМГИЙН НАРИЙН ГАЗАР. Өмнө нь энэ хэв маяг `(?:\d{1,2}\s*…)+` гэж
 * бичигдсэн байсан тул ТООТЫГ ЗАЛГИДАГ байв:
 *
 *   "2-257 9 SAR"  →  25 + 7 + 9 + SAR  гэж уншаад БҮГДИЙГ нь устгана
 *   "301 9САР"     →  30 + 1 + 9 + САР  →  301 тоот алга болно
 *
 * Хамгаалалт хоёр давхар:
 *   (?<!\d)   — өмнөх тэмдэгт цифр биш (урт тооны сүүлийг таслахгүй)
 *   (?!\d)    — араас нь цифр үргэлжлэхгүй ("25" гэж 257-г таслахгүй)
 *
 * Эдгээр хоёр нь "2-257 9 SAR"-ыг хамгаалахад ХАНГАЛТТАЙ: "257"-оос эхлэх
 * оролдлого бүр (?!\d)-д унана. Тиймээс "305-7SAR" гэх зураасны дараах
 * сарыг ч таслаж чадна — эс бөгөөс 7 нь бүртгэлтэй ТООТ учир "7 эсвэл 305"
 * гэсэн хуурамч эргэлзээ үүсгэнэ.
 */
const RE_MONTH = new RegExp(
  `(?<!\\d)(?:\\d{1,2}(?!\\d)\\s*[-НNЫ]?\\s*)+(?:${SAR})\\w*`,
  'g',
);

/**
 * "2668SAR" → "266 8SAR" — тоот ба сар зай авалгүй нийлсэн тохиолдол.
 *
 * Тоот 3–4 оронтой, сар 1–2 оронтой тул шунахай тоолол нь эхний 3-4 орныг
 * тоот гэж үзээд үлдсэнийг сар болгоно. Зай тавихгүй бол дараагийн алхам
 * үүнийг «2668» гэсэн нэг тоо гэж уншина.
 */
const RE_GLUED_MONTH = new RegExp(`(\\d{3,4})(\\d{1,2})(?=\\s*(?:${SAR}))`, 'g');

/** "2-Р ОРЦ" · "2-ОРЦ" · "1 орц" · "2R ORTS" — тоо нь ӨМНӨ нь */
const RE_ENTRANCE = new RegExp(`\\d{1,2}\\s*-?\\s*${R}?\\s*-?\\s*(?:${ORTS})`, 'g');

/**
 * "ОРЦ2" · "ORTS 2" — тоо нь ХОЙНО нь бичигдсэн хувилбар.
 *
 * Зөвхөн араас нь зураас эсвэл зай ирвэл авна ("ОРЦ2-197"). Үгүй бол
 * "ОРЦ213" гэсэн бичлэгээс 213 тоотыг андуурч устгах эрсдэлтэй.
 */
const RE_ENTRANCE_SUFFIX = new RegExp(`(?:${ORTS})\\s*-?\\s*\\d{1,2}(?=\\s*-|\\s|$)`, 'g');

/** "323р байр" · "12 байр" */
const RE_BUILDING = new RegExp(`\\d{1,4}\\s*-?\\s*${R}?\\s*(?:${BAIR})`, 'g');

/**
 * Дуут хэсгүүдийг устгана. Үлдсэн тоонууд л тоот байх боломжтой.
 *
 * Жишээ:
 *   "323Р БАЙР 1 ОРЦ 127 ТООТ УСНЫ ҮНЭ"  →  "127 ТООТ УСНЫ ҮНЭ"
 *   "2R ORTS 289TOOT 7SAR"               →  "289TOOT"
 */
export function stripNoise(text: string): string {
  return text
    .replace(RE_LONG_NUMBER, ' ')
    .replace(RE_BUILDING, ' ')
    .replace(RE_ENTRANCE, ' ')
    .replace(RE_ENTRANCE_SUFFIX, ' ')
    // Сарыг таслахаас ӨМНӨ наалдсан тоог салгана: "2668SAR" → "266 8SAR"
    .replace(RE_GLUED_MONTH, '$1 $2')
    .replace(RE_MONTH, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
