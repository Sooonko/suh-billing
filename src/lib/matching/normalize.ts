/**
 * Гүйлгээний утгыг цэвэрлэх / нормчлох давхарга.
 *
 * Банкны хуулга дээр нэг л зүйлийг олон янзаар бичсэн байдаг:
 *   "184ТООТУС"  "2-236TOOT 6N SAR US"  "2R ORTS 289TOOT"  "323р байр 1 орц 127 тоот"
 *
 * Хамгийн эвгүй нь ЛАТИН/КИРИЛЛ ХОЛИЛДСОН байдаг явдал:
 *   "8CAP" гэдэг нь латин C-A-P үсгээр бичсэн "8САР".
 *
 * Бүх текстийг нэг цагаан толгой руу хөрвүүлэх нь АЮУЛТАЙ (жинхэнэ латин үгийг
 * эвдэнэ), тиймээс түлхүүр үг бүрийг латин/кирилл хосыг зэрэг зөвшөөрдөг
 * тэмдэгтийн ангиар (character class) илэрхийлнэ.
 */

// ---- Латин ба кирилл хос тэмдэгтүүд — "аль нь ч байж болно" ------------------
const A = '[АA]';
const S = '[СCS]'; // С (кирилл) · C (латин) · S
const R = '[РPR]'; // Р (кирилл) · P (латин) · R
const O = '[ОO]';
const T = '[ТT]';
const TS = '[ЦC]'; // Ц (кирилл) · C (латин)

/** "ТООТ" / "TOOT" / холимог */
export const TOOT = `${T}${O}${O}${T}`;
/** "САР" / "SAR" / "CAP" */
export const SAR = `${S}${A}${R}`;
/** "ORTS" (урт хувилбарыг ЭХЭЛЖ шалгана) / "ОРЦ" */
export const ORTS = `${O}${R}${T}${S}|${O}${R}${TS}`;
/** "БАЙР" / "BAIR" / "BAYR" */
export const BAIR = `Б${A}[ЙЯ]${R}|B${A}[IY]${R}`;

/**
 * Үндсэн нормчлол:
 *  - том үсэг рүү хөрвүүлнэ
 *  - цэг, таслал, хаалт зэргийг зайгаар солино
 *  - олон зайг нэг болгоно
 *
 * NB: "-" тэмдэг ба цифрийг ХАДГАЛНА — "2-257" хэлбэр тоот таахад хэрэгтэй.
 */
export function normalize(raw: string): string {
  return raw
    .toUpperCase()
    .replace(/[.,;:/\\()[\]"'`_]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// ---- "Дуут" хэсгүүд: тоо агуулдаг ч ТООТ БИШ --------------------------------

/** 7+ оронтой тоо = утас / дансны дугаар. Тоот хэзээ ч ийм урт биш. */
const RE_LONG_NUMBER = /\d{7,}/g;

/** "7 SAR" · "8CAP" · "6N SAR" · "7-SAR" · "6 7 САРЫН" (олон сар хамт) */
const RE_MONTH = new RegExp(`(?:\\d{1,2}\\s*[-НNЫ]?\\s*)+(?:${SAR})\\w*`, 'g');

/** "2-Р ОРЦ" · "2-ОРЦ" · "1 орц" · "2R ORTS" */
const RE_ENTRANCE = new RegExp(`\\d{1,2}\\s*-?\\s*${R}?\\s*-?\\s*(?:${ORTS})`, 'g');

/** "323р байр" · "12 байр" */
const RE_BUILDING = new RegExp(`\\d{1,4}\\s*-?\\s*${R}?\\s*(?:${BAIR})`, 'g');

/**
 * Дуут хэсгүүдийг устгана. Үлдсэн тоонууд л тоот байх боломжтой.
 *
 * Жишээ:
 *   "323Р БАЙР 1 ОРЦ 127 ТООТ УСНЫ ҮНЭ"  →  "127 ТООТ УСНЫ ҮНЭ"
 *   "2R ORTS 289TOOT 7SAR"               →  "289TOOT"
 */
export function stripNoise(text: string): string {
  return text
    .replace(RE_LONG_NUMBER, ' ')
    .replace(RE_BUILDING, ' ')
    .replace(RE_ENTRANCE, ' ')
    .replace(RE_MONTH, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
