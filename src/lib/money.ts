/**
 * Мөнгөний нарийвчлалын хил.
 *
 * ЯАГААД ХЭРЭГТЭЙ ВЭ:
 * Нэхэмжлэл 2 аравтын оронтой бодогддог (цахилгаан: 42,183.54₮), харин
 * банкаар мөнгө БҮХЭЛ төгрөгөөр хөдөлдөг. Тиймээс айл бүтэн төлсөн ч
 * хэдэн мөнгөний үлдэгдэл үлддэг:
 *
 *   115 тоот · цахилгаан
 *     нэхэмжилсэн  85,404.38₮
 *     төлсөн       85,404.36₮
 *     үлдэгдэл          0.02₮   ← «дутуу төлсөн» гэж харагдана
 *
 * Дэлгэц дээр дүн нь бөөрөнхийлөгдөж «0₮» гэж гарах атлаа төлөв нь
 * «дутуу төлсөн» гэж гардаг байсан — хэрэглэгчийн нүдэнд зөрчил.
 *
 * Хэн ч 1₮-ийн өрийг нэхдэггүй тул үүнээс бага үлдэгдлийг ТЭГ гэж үзнэ.
 */
export const SETTLED_EPSILON = 1;

/** Үлдэгдэл бодитоор хаагдсан уу (1₮-өөс бага зөрүүг үл хэрэгсэнэ) */
export function isSettled(balance: number): boolean {
  return Math.abs(balance) < SETTLED_EPSILON;
}

/** Бодитоор өртэй юу */
export function hasDebt(balance: number): boolean {
  return balance >= SETTLED_EPSILON;
}

/** Бодитоор илүү төлсөн үү */
export function hasOverpaid(balance: number): boolean {
  return balance <= -SETTLED_EPSILON;
}
